/**
 * Cloudflare Pages Functions /api/* -> private Backlink Command Center API.
 * The operator session remains an HttpOnly, SameSite=Strict cookie.
 * This function NEVER talks to DataForSEO or Gmail and exposes no provider secret.
 * Cloudflare env: BACKLINK_API_ORIGIN (HTTPS tunnel origin), BACKLINK_PROXY_SECRET.
 */

const SECURITY_HEADERS = {
  'Cache-Control': 'no-store, private',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'no-referrer',
  'X-Robots-Tag': 'noindex, nofollow, noarchive',
};

function unavailable(message, status = 503) {
  return new Response(JSON.stringify({detail: message}), {
    status,
    headers: {'Content-Type': 'application/json; charset=utf-8', ...SECURITY_HEADERS},
  });
}

function upstreamOrigin(env) {
  const originText = env?.BACKLINK_API_ORIGIN;
  const key = env?.BACKLINK_PROXY_SECRET;
  if (typeof originText !== 'string' || typeof key !== 'string' || key.length < 32) return null;
  try {
    const url = new URL(originText);
    if (url.protocol !== 'https:' || url.username || url.password || url.pathname !== '/' || url.search || url.hash) return null;
    return {origin: url.origin, key};
  } catch {return null;}
}

/**
 * Incoming API access is scoped to the /api/ route. The upstream hostname is
 * read from deployment bindings only, never from request headers or query text.
 */
export async function onRequest(context) {
  const {request, env} = context;
  const source = new URL(request.url);
  if (!source.pathname.startsWith('/api/') && source.pathname !== '/api') return unavailable('Not found', 404);

  const endpoint = upstreamOrigin(env);
  if (!endpoint) return unavailable('Backend unavailable. Configure the private API connection in Cloudflare Pages.');

  const target = new URL(source.pathname + source.search, endpoint.origin);
  const headers = new Headers();
  for (const header of ['accept', 'content-type', 'cookie', 'x-csrf-token']) {
    const value = request.headers.get(header);
    if (value) headers.set(header, value);
  }
  headers.set('X-Backlink-Proxy-Token', endpoint.key);
  // This header is generated by Cloudflare, not accepted from the browser.
  const clientIp = request.headers.get('CF-Connecting-IP');
  if (clientIp) headers.set('X-Backlink-Client-IP', clientIp);

  let upstream;
  try {
    const init = {method: request.method, headers, redirect: 'manual'};
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      init.body = request.body;
      init.duplex = 'half';
    }
    upstream = await fetch(new Request(target, init));
  } catch {
    return unavailable('Private worker API is unreachable. Check your RackNerd service and Cloudflare Tunnel.');
  }

  // Do not let an upstream redirect expose the private tunnel hostname.
  if (upstream.status >= 300 && upstream.status < 400) return unavailable('Unexpected upstream redirect', 502);

  const responseHeaders = new Headers(SECURITY_HEADERS);
  for (const h of ['content-type', 'content-disposition', 'set-cookie', 'retry-after']) {
    const v = upstream.headers.get(h);
    if (v) responseHeaders.set(h, v);
  }
  return new Response(upstream.body, {status: upstream.status, headers: responseHeaders});
}
